    // Gregorian date of 1 Muharram START_YEAR AH, per the table definition.
    private val ANCHOR_EPOCH_DAY = LocalDate.of(1882, 11, 12).toEpochDay()

    private fun monthLength(year: Int, month: Int): Int =
        if ((MONTH_MASKS[year - START_YEAR] shr (12 - month) and 1L) == 1L) 30 else 29

    fun yearLength(year: Int): Int = 348 + Integer.bitCount(MONTH_MASKS[year - START_YEAR].toInt())

    fun getDaysInMonth(year: Int, month: Int): Int =
        if (year in START_YEAR..END_YEAR) monthLength(year, month) else 30

    private fun daysUpToYear(year: Int): Long {
        var total = 0L
        var y = START_YEAR
        while (y < year) {
            total += yearLength(y)
            y++
        }
        return total
    }

    /** Gregorian -> Hijri [year, month, day]. Returns null before START_YEAR. */
    fun toHijri(gYear: Int, gMonth: Int, gDay: Int): Triple<Int, Int, Int>? {
        val date = try {
            LocalDate.of(gYear, gMonth, gDay)
        } catch (_: Exception) {
            return null
        }
        var days = date.toEpochDay() - ANCHOR_EPOCH_DAY
        if (days < 0) return null
        var year = START_YEAR
        var yl = yearLength(year)
        while (days >= yl) {
            days -= yl
            year++
            if (year > END_YEAR) return null
            yl = yearLength(year)
        }
        var month = 1
        var ml = monthLength(year, month)
        while (days >= ml && month <= 12) {
            days -= ml
            month++
            ml = monthLength(year, month)
        }
        return Triple(year, month, days.toInt() + 1)
    }

    /** Hijri -> Gregorian [year, month, day]. Returns null outside range. */
    fun toGregorian(hYear: Int, hMonth: Int, hDay: Int): Triple<Int, Int, Int>? {
        if (hYear < START_YEAR || hYear > END_YEAR) return null
        if (hMonth < 1 || hMonth > 12 || hDay < 1 || hDay > getDaysInMonth(hYear, hMonth)) return null
        var days = daysUpToYear(hYear)
        var m = 1
        while (m < hMonth) {
            days += monthLength(hYear, m)
            m++
        }
        days += (hDay - 1)
        val epochDay = ANCHOR_EPOCH_DAY + days
        return try {
            val d = LocalDate.ofEpochDay(epochDay)
            Triple(d.year, d.monthValue, d.dayOfMonth)
        } catch (_: Exception) {
            null
        }
    }
